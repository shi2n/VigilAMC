export function getTaskActionDictionary(langCode = 'en'): TaskActionDictionary {
  const code = (langCode || 'en').toLowerCase().trim();
  return TASK_ACTION_TRANSLATIONS[code] || TASK_ACTION_TRANSLATIONS.en;
}

export function getActionTakenLabel(
  actionTaken: string | null | undefined,
  langCode = 'en'
): string {
  const dict = getTaskActionDictionary(langCode);
  switch (actionTaken) {
    case 'NO_ACTION':
      return dict.actionNoAction;
    case 'REFILLED':
      return dict.actionRefilled;
    case 'REPLACED':
      return dict.actionReplaced;
    case 'SERVICED':
      return dict.actionServiced;
    case 'MISSING':
      return dict.actionMissing;
    case 'OTHER':
      return dict.actionOther;
    default:
      return dict.dashboardNoActionRecorded;
  }
}
