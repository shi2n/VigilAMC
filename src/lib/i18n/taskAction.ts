export const WORK_ORDER_ACTION_TAKEN_VALUES = [
  'NO_ACTION',
  'REFILLED',
  'REPLACED',
  'SERVICED',
  'MISSING',
  'OTHER',
] as const;

export type WorkOrderActionTakenValue = (typeof WORK_ORDER_ACTION_TAKEN_VALUES)[number];

export function isValidWorkOrderActionTaken(value: unknown): value is WorkOrderActionTakenValue {
  return (
    typeof value === 'string' &&
    (WORK_ORDER_ACTION_TAKEN_VALUES as readonly string[]).includes(value)
  );
}

export function validateTaskCompletionAction(
  actionTaken: unknown,
  notes: unknown
): { ok: true; actionTaken: WorkOrderActionTakenValue; notes: string | null } | { ok: false; error: string } {
  const normalizedAction =
    actionTaken === undefined || actionTaken === null || actionTaken === ''
      ? 'NO_ACTION'
      : String(actionTaken).trim().toUpperCase();

  if (!isValidWorkOrderActionTaken(normalizedAction)) {
    return {
      ok: false,
      error: `Invalid action_taken value: ${String(actionTaken)}`,
    };
  }

  const trimmedNotes = typeof notes === 'string' ? notes.trim() : '';

  if (normalizedAction === 'OTHER' && trimmedNotes.length < 4) {
    return {
      ok: false,
      error: 'Remarks must be at least 4 characters when Action Taken is Other.',
    };
  }

  return {
    ok: true,
    actionTaken: normalizedAction,
    notes: trimmedNotes.length > 0 ? trimmedNotes : null,
  };
}

