export function getPhotoEvidenceDictionary(lang?: string | null): PhotoEvidenceDictionary {
  const code = (lang || 'en').toLowerCase().trim();
  return PHOTO_EVIDENCE_TRANSLATIONS[code] || PHOTO_EVIDENCE_TRANSLATIONS.en;
}

export function formatPhotoTemplate(template: string, count: number): string {
  return template.replace(/\{n\}/g, String(count));
}
