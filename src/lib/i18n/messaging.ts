export function getMessagingDictionary(langCode?: string | null): MessagingDictionary {
  const code = String(langCode || 'en').trim().toLowerCase();
  return MESSAGING_TRANSLATIONS[code] || MESSAGING_TRANSLATIONS.en;
}

export function formatMsgTemplate(template: string, vars: Record<string, string | number>): string {
  let out = template;
  for (const [k, v] of Object.entries(vars)) {
    out = out.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return out;
}

