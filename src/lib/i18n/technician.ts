/**
 * Format date in locale-aware style
 */
export function formatLocalizedDate(date: Date | string | number, lang: SupportedLanguage): string {
  try {
    const d = new Date(date);
    const meta = SUPPORTED_LANGUAGES.find((l) => l.code === lang) || SUPPORTED_LANGUAGES[0];
    return new Intl.DateTimeFormat(meta.bcp47, {
      weekday: 'short',
      day: 'numeric',
      month: 'short',
      year: 'numeric',
    }).format(d);
  } catch {
    return new Date(date).toLocaleDateString();
  }
}

/**
 * Format time in locale-aware style
 */
export function formatLocalizedTime(date: Date | string | number, lang: SupportedLanguage): string {
  try {
    const d = new Date(date);
    const meta = SUPPORTED_LANGUAGES.find((l) => l.code === lang) || SUPPORTED_LANGUAGES[0];
    return new Intl.DateTimeFormat(meta.bcp47, {
      hour: '2-digit',
      minute: '2-digit',
      hour12: true,
    }).format(d);
  } catch {
    return new Date(date).toLocaleTimeString();
  }
}

/**
 * Format full datetime string for stamped photo metadata
 */
export function formatLocalizedDateTime(date: Date | string | number, lang: SupportedLanguage): string {
  try {
    const d = new Date(date);
    const meta = SUPPORTED_LANGUAGES.find((l) => l.code === lang) || SUPPORTED_LANGUAGES[0];
    return new Intl.DateTimeFormat(meta.bcp47, {
      weekday: 'short',
      day: '2-digit',
      month: 'short',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
      hour12: false,
    }).format(d);
  } catch {
    return new Date(date).toISOString();
  }
}
